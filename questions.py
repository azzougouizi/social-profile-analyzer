def get_questions(subject):
    """
    ترجع جميع أسئلة المادة المطلوبة.
    """

    return QUESTIONS.get(
        subject,
        []
    )


def get_random_questions(subject, amount=10):
    """
    تختار أسئلة عشوائية بدون تكرار
    داخل الاختبار الواحد.
    """

    questions = get_questions(subject)

    if not questions:
        return []

    amount = min(
        amount,
        len(questions)
    )

    import random

    return random.sample(
        questions,
        amount
    )


def total_questions():
    """
    حساب إجمالي عدد الأسئلة في البنك.
    """

    return sum(
        len(items)
        for items in QUESTIONS.values()
    )
